//! macOS secret clipboard implementation.
//!
//! `CurrentHostOnly` keeps the item out of Universal Clipboard. The custom
//! pasteboard types are conventions honoured by password managers and common
//! clipboard-history tools; they are advisory, not an OS access-control
//! boundary. Calls should originate on the GPUI/main thread.
//!
//! Every item also carries [`SECRET_MARKER_TYPE`], a type only FerrisPass
//! writes. It is how a new launch recognises a copy an earlier run left
//! behind, by asking for the type and never for the contents.
//!
//! Outside the tests this file never calls a method that reads contents
//! (`stringForType`, `dataForType`, `propertyListForType`, `pasteboardItems`,
//! `readObjectsForClasses`). `clipboard_code_never_reads_pasteboard_content`
//! in `tests/architecture.rs` holds that.

use objc2::{rc::Retained, runtime::ProtocolObject};
use objc2_app_kit::{
    NSPasteboard, NSPasteboardAccessBehavior, NSPasteboardContentsOptions, NSPasteboardItem,
    NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSString};

use super::{AccessBehavior, ClipboardChangeCount, ClipboardError, ClipboardResult};

const STRING_TYPE: &str = "public.utf8-plain-text";
const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
/// Private to FerrisPass, named after the bundle identifier
/// `rs.ferrispass.app`. Like the types above it carries an empty string.
const SECRET_MARKER_TYPE: &str = "rs.ferrispass.clipboard.secret";

/// Write a secret to the general pasteboard and return its generation.
///
/// No copy of `text` is kept by this module after AppKit accepts the item.
/// The pasteboard item is restricted to this Mac and carries the concealed,
/// transient, and auto-generated hints used by clipboard-history tools, plus
/// FerrisPass's own marker.
pub fn write_secret_text(text: &str) -> ClipboardResult<ClipboardChangeCount> {
    write_secret_to(&NSPasteboard::generalPasteboard(), text)
}

/// Clear the general pasteboard only if it still contains the generation
/// returned by [`write_secret_text`]. Returns `false` when another process or
/// the user has changed the clipboard in the meantime.
///
/// AppKit has no atomic compare-and-clear operation, so this is the strongest
/// check its change-count API provides.
pub fn clear_if_unchanged(expected: ClipboardChangeCount) -> ClipboardResult<bool> {
    Ok(clear_if_unchanged_on(
        &NSPasteboard::generalPasteboard(),
        expected,
    ))
}

/// The user's "Paste from Other Apps" setting for FerrisPass. Reading it
/// never shows the paste prompt.
///
/// The property exists from macOS 15.4. On an older system this reports
/// `Default`, which the launch check treats as "do not look".
pub fn access_behavior() -> AccessBehavior {
    if !objc2::available!(macos = 15.4) {
        return AccessBehavior::Default;
    }
    access_behavior_of(&NSPasteboard::generalPasteboard())
}

/// Whether the general pasteboard holds an item with our marker type. Asks
/// for that one type with `availableTypeFromArray` and reads no contents.
pub fn has_own_marker() -> bool {
    has_own_marker_on(&NSPasteboard::generalPasteboard())
}

/// The general pasteboard's current generation.
pub fn change_count() -> ClipboardChangeCount {
    ClipboardChangeCount::from_raw(NSPasteboard::generalPasteboard().changeCount())
}

fn access_behavior_of(pasteboard: &NSPasteboard) -> AccessBehavior {
    access_behavior_from(pasteboard.accessBehavior())
}

/// AppKit's value as ours. Only `AlwaysAllow` lets the launch check look at
/// the pasteboard, so nothing else may ever become `AlwaysAllow` here.
fn access_behavior_from(raw: NSPasteboardAccessBehavior) -> AccessBehavior {
    match raw {
        NSPasteboardAccessBehavior::Ask => AccessBehavior::Ask,
        NSPasteboardAccessBehavior::AlwaysAllow => AccessBehavior::AlwaysAllow,
        NSPasteboardAccessBehavior::AlwaysDeny => AccessBehavior::AlwaysDeny,
        // `Default`, and any value a later macOS adds: neither allows a look.
        _ => AccessBehavior::Default,
    }
}

fn has_own_marker_on(pasteboard: &NSPasteboard) -> bool {
    let wanted = NSArray::from_retained_slice(&[NSString::from_str(SECRET_MARKER_TYPE)]);
    pasteboard.availableTypeFromArray(&wanted).is_some()
}

fn write_secret_to(pasteboard: &NSPasteboard, text: &str) -> ClipboardResult<ClipboardChangeCount> {
    // Build the complete item before touching the pasteboard. This avoids a
    // window where a history manager could observe the string type before the
    // concealed/transient markers have been attached.
    let item = NSPasteboardItem::new();
    let value = NSString::from_str(text);
    let empty = NSString::from_str("");
    let types = [
        (STRING_TYPE, value.as_ref()),
        (CONCEALED_TYPE, empty.as_ref()),
        (TRANSIENT_TYPE, empty.as_ref()),
        (AUTO_GENERATED_TYPE, empty.as_ref()),
        (SECRET_MARKER_TYPE, empty.as_ref()),
    ];

    for (type_name, value) in types {
        let pasteboard_type = NSString::from_str(type_name);
        if !item.setString_forType(value, &pasteboard_type) {
            return Err(ClipboardError::ItemConstructionFailed);
        }
    }

    let item: Retained<ProtocolObject<dyn NSPasteboardWriting>> =
        ProtocolObject::from_retained(item);
    let objects = NSArray::from_retained_slice(&[item]);

    let prepared_count = ClipboardChangeCount::from_raw(
        pasteboard.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly),
    );
    if !pasteboard.writeObjects(&objects) {
        // Only clear the empty/partial generation we prepared. If another app
        // has already replaced it, leave that newer clipboard untouched.
        let _ = clear_if_unchanged_on(pasteboard, prepared_count);
        return Err(ClipboardError::WriteFailed);
    }

    // Return the generation `prepareForNewContents` reserved for *our*
    // write, not a live `changeCount()` read: another app writing between
    // `writeObjects` and that read would hand us its generation, and the
    // auto-clear timer would later erase that app's clipboard content -
    // exactly the race `clear_if_unchanged` exists to prevent.
    Ok(prepared_count)
}

fn clear_if_unchanged_on(pasteboard: &NSPasteboard, expected: ClipboardChangeCount) -> bool {
    if pasteboard.changeCount() != expected.into_raw() {
        return false;
    }

    pasteboard.clearContents();
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text_for_type(pasteboard: &NSPasteboard, type_name: &str) -> Option<String> {
        let pasteboard_type = NSString::from_str(type_name);
        pasteboard
            .stringForType(&pasteboard_type)
            .map(|value| value.to_string())
    }

    /// A plain copy, the way another app makes one: one item, text only.
    fn write_foreign_text(pasteboard: &NSPasteboard, text: &str) {
        let item = NSPasteboardItem::new();
        assert!(
            item.setString_forType(&NSString::from_str(text), &NSString::from_str(STRING_TYPE))
        );
        let item: Retained<ProtocolObject<dyn NSPasteboardWriting>> =
            ProtocolObject::from_retained(item);
        pasteboard.clearContents();
        assert!(pasteboard.writeObjects(&NSArray::from_retained_slice(&[item])));
    }

    #[test]
    fn secret_item_has_all_privacy_types() {
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        let token = write_secret_to(&pasteboard, "test-secret").expect("write secret");

        assert_eq!(
            text_for_type(&pasteboard, STRING_TYPE).as_deref(),
            Some("test-secret")
        );
        assert_eq!(
            text_for_type(&pasteboard, CONCEALED_TYPE).as_deref(),
            Some("")
        );
        assert_eq!(
            text_for_type(&pasteboard, TRANSIENT_TYPE).as_deref(),
            Some("")
        );
        assert_eq!(
            text_for_type(&pasteboard, AUTO_GENERATED_TYPE).as_deref(),
            Some("")
        );
        assert_eq!(
            text_for_type(&pasteboard, SECRET_MARKER_TYPE).as_deref(),
            Some("")
        );
        assert_eq!(pasteboard.changeCount(), token.into_raw());
    }

    #[test]
    fn secret_item_carries_private_marker() {
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        assert!(!has_own_marker_on(&pasteboard), "a new pasteboard is empty");

        write_secret_to(&pasteboard, "test-secret").expect("write secret");
        assert!(has_own_marker_on(&pasteboard));

        let current = ClipboardChangeCount::from_raw(pasteboard.changeCount());
        assert!(clear_if_unchanged_on(&pasteboard, current));
        assert!(
            !has_own_marker_on(&pasteboard),
            "clearing has to take the marker with it"
        );
    }

    #[test]
    fn has_own_marker_is_false_for_foreign_text() {
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        write_foreign_text(&pasteboard, "a note");
        assert!(!has_own_marker_on(&pasteboard));

        // Our copy, then someone else's: only the newer item counts.
        write_secret_to(&pasteboard, "test-secret").expect("write secret");
        write_foreign_text(&pasteboard, "a later note");
        assert!(!has_own_marker_on(&pasteboard));
        assert_eq!(
            text_for_type(&pasteboard, STRING_TYPE).as_deref(),
            Some("a later note")
        );
    }

    /// The raw values are the ones in Apple's `NSPasteboard.h`: 0 Default,
    /// 1 Ask, 2 AlwaysAllow, 3 AlwaysDeny. Anything else is a value this
    /// build doesn't know and must not open the launch check.
    #[test]
    fn access_behavior_maps_every_appkit_value() {
        let cases = [
            (0, AccessBehavior::Default),
            (1, AccessBehavior::Ask),
            (2, AccessBehavior::AlwaysAllow),
            (3, AccessBehavior::AlwaysDeny),
            (4, AccessBehavior::Default),
            (-1, AccessBehavior::Default),
            (isize::MAX, AccessBehavior::Default),
        ];
        for (raw, expected) in cases {
            assert_eq!(
                access_behavior_from(NSPasteboardAccessBehavior(raw)),
                expected,
                "raw accessBehavior {raw}"
            );
        }
    }

    /// Apple documents every pasteboard other than the general one as always
    /// allowing access. Reading the setting there shows that the mapping
    /// works on a real value without touching the general pasteboard.
    #[test]
    fn private_pasteboard_reports_always_allow() {
        if !objc2::available!(macos = 15.4) {
            return;
        }
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        assert_eq!(access_behavior_of(&pasteboard), AccessBehavior::AlwaysAllow);
    }

    #[test]
    fn delayed_clear_does_not_erase_newer_clipboard_contents() {
        let pasteboard = NSPasteboard::pasteboardWithUniqueName();
        let stale = write_secret_to(&pasteboard, "first").expect("write first");
        let current = write_secret_to(&pasteboard, "second").expect("write second");

        assert!(!clear_if_unchanged_on(&pasteboard, stale));
        assert_eq!(
            text_for_type(&pasteboard, STRING_TYPE).as_deref(),
            Some("second")
        );

        assert!(clear_if_unchanged_on(&pasteboard, current));
        assert_eq!(text_for_type(&pasteboard, STRING_TYPE), None);
    }
}
