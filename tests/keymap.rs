//! The key binding inventory and the one binding whose winner depends on focus.
//!
//! GPUI Kit registers its own bindings in `gpui_component::init`, next to the
//! app's in `actions::init`. A Kit upgrade can add, drop or rebind keys without
//! a single line of FerrisPass changing, so the full keymap is pinned as a
//! snapshot: any difference fails here and has to be explained before the
//! snapshot is regenerated.
//!
//! A text snapshot cannot say which binding wins when two contexts bind the
//! same keys. Cmd+C is that case (the entry list copies the password, a text
//! field copies its selection), and so is Cmd+F (the shell focuses the vault
//! search, a text field keeps the key), so both get headless dispatch tests.
//!
//! Regenerate the snapshot after a reviewed change with
//! `UPDATE_KEYMAP_SNAPSHOT=1 cargo test --locked --test keymap`.

use std::path::PathBuf;

use ferrispass::app::actions::{self, APP_CONTEXT, CopyPassword, FocusSearch};
use gpui::{
    AppContext as _, Context, Entity, FocusHandle, InteractiveElement as _, IntoElement,
    ParentElement as _, Render, Styled as _, TestAppContext, Window, WindowHandle, div,
};
use gpui_component::{
    Root,
    input::{Input, InputState},
};

const SNAPSHOT: &str = "tests/snapshots/keymap.txt";

const SNAPSHOT_HEADER: &str = "\
# Key binding inventory: gpui_component::init, then ferrispass::app::actions::init,
# in registration order (a later binding wins over an earlier one in the same context).
# Format: keystrokes<TAB>context predicate (- = none)<TAB>action
# Generated by tests/keymap.rs; regenerate with UPDATE_KEYMAP_SNAPSHOT=1 after review.
";

/// The inspector toggle `gpui_component::init` registers in every build with
/// `debug_assertions`, which includes every test build. Release builds compile
/// the inspector out (no `inspector` feature is enabled anywhere in the tree),
/// so the snapshot describes the shipped keymap without it.
const DEBUG_ONLY_INSPECTOR: &str = "alt-cmd-i\t-\tinspector::ToggleInspector";

fn binding_lines(cx: &mut TestAppContext) -> Vec<String> {
    cx.update(|cx| {
        gpui_component::init(cx);
        actions::init(cx);
        let keymap = cx.key_bindings();
        let keymap = keymap.borrow();
        keymap
            .bindings()
            .map(|binding| {
                let keys = binding
                    .keystrokes()
                    .iter()
                    .map(|keystroke| keystroke.unparse())
                    .collect::<Vec<_>>()
                    .join(" ");
                let context = binding
                    .predicate()
                    .map(|predicate| predicate.to_string())
                    .unwrap_or_else(|| "-".to_string());
                format!("{keys}\t{context}\t{}", binding.action().name())
            })
            .collect()
    })
}

#[gpui::test]
fn keymap_matches_snapshot(cx: &mut TestAppContext) {
    let lines = binding_lines(cx);

    let (inspector, shipped): (Vec<String>, Vec<String>) = lines
        .into_iter()
        .partition(|line| line.contains("inspector::"));
    let expected_inspector: Vec<String> = if cfg!(debug_assertions) {
        vec![DEBUG_ONLY_INSPECTOR.to_string()]
    } else {
        Vec::new()
    };
    assert_eq!(
        inspector, expected_inspector,
        "the inspector bindings changed; only the debug-build toggle may be filtered out"
    );

    let actual = format!("{SNAPSHOT_HEADER}{}\n", shipped.join("\n"));
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(SNAPSHOT);
    if std::env::var_os("UPDATE_KEYMAP_SNAPSHOT").is_some() {
        std::fs::write(&path, &actual).expect("write keymap snapshot");
        return;
    }
    let expected = std::fs::read_to_string(&path).expect("read keymap snapshot");
    if actual != expected {
        let missing: Vec<&str> = expected
            .lines()
            .filter(|line| !line.starts_with('#') && !actual.lines().any(|a| a == *line))
            .collect();
        let added: Vec<&str> = actual
            .lines()
            .filter(|line| !line.starts_with('#') && !expected.lines().any(|e| e == *line))
            .collect();
        panic!(
            "keymap differs from {SNAPSHOT} (order or content).\n\
             missing: {missing:#?}\nadded: {added:#?}\n\
             Explain every difference, then regenerate with UPDATE_KEYMAP_SNAPSHOT=1."
        );
    }
}

/// Stand-in for `AppShell`'s root: the `FerrisPass` key context on a focusable
/// div that handles `CopyPassword` and `FocusSearch`, with a text field inside it.
struct Shell {
    focus: FocusHandle,
    field: Entity<InputState>,
    copy_password_calls: usize,
    focus_search_calls: usize,
}

impl Render for Shell {
    fn render(&mut self, _window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        div()
            .key_context(APP_CONTEXT)
            .track_focus(&self.focus)
            .on_action(cx.listener(|shell: &mut Shell, _: &CopyPassword, _, _| {
                shell.copy_password_calls += 1;
            }))
            .on_action(cx.listener(|shell: &mut Shell, _: &FocusSearch, _, _| {
                shell.focus_search_calls += 1;
            }))
            .size_full()
            .child(Input::new(&self.field))
    }
}

fn open_shell(cx: &mut TestAppContext) -> (WindowHandle<Root>, Entity<Shell>) {
    cx.update(|cx| {
        gpui_component::init(cx);
        actions::init(cx);
    });
    let mut shell = None;
    let window = cx.add_window(|window, cx| {
        let field = cx.new(|cx| {
            let mut state = InputState::new(window, cx);
            state.set_value("plain text", window, cx);
            state
        });
        let view = cx.new(|cx| Shell {
            focus: cx.focus_handle(),
            field,
            copy_password_calls: 0,
            focus_search_calls: 0,
        });
        shell = Some(view.clone());
        Root::new(view, window, cx)
    });
    cx.run_until_parked();
    (window, shell.expect("shell view"))
}

#[gpui::test]
fn cmd_c_copies_the_password_from_the_list_but_not_from_a_text_field(cx: &mut TestAppContext) {
    let (window, shell) = open_shell(cx);

    // Focus on the shell itself: what the entry list has when no field is focused.
    window
        .update(cx, |_, window, cx| {
            let focus = shell.read(cx).focus.clone();
            window.focus(&focus, cx);
        })
        .unwrap();
    cx.run_until_parked();
    cx.simulate_keystrokes(window.into(), "cmd-c");
    assert_eq!(
        shell.read_with(cx, |shell, _| shell.copy_password_calls),
        1,
        "Cmd+C in the entry list must copy the password"
    );
    assert_eq!(cx.read_from_clipboard(), None);

    // Focus in a text field: Cmd+C is the field's own Copy.
    window
        .update(cx, |_, window, cx| {
            let field = shell.read(cx).field.clone();
            field.update(cx, |state, cx| state.focus(window, cx));
        })
        .unwrap();
    cx.run_until_parked();
    // Without a selection the field has nothing to copy, and still keeps the
    // gesture: it must not fall through to the password.
    cx.simulate_keystrokes(window.into(), "cmd-c");
    assert_eq!(
        shell.read_with(cx, |shell, _| shell.copy_password_calls),
        1,
        "Cmd+C in a focused text field without a selection must not copy the password"
    );
    assert_eq!(cx.read_from_clipboard(), None);
    cx.simulate_keystrokes(window.into(), "cmd-a cmd-c");
    assert_eq!(
        shell.read_with(cx, |shell, _| shell.copy_password_calls),
        1,
        "Cmd+C in a focused text field must not copy the password"
    );
    assert_eq!(
        cx.read_from_clipboard().and_then(|item| item.text()),
        Some("plain text".to_string()),
        "Cmd+C in a focused text field copies its selection"
    );
}

/// Cmd+F is bound twice as well: `input::Search` in the field, `FocusSearch` in
/// the shell. Up to GPUI Kit 0.5 a field that is not searchable (none in
/// FerrisPass is) swallowed `Search`, so Cmd+F inside a field did nothing.
/// Since 0.7 such a field passes it on and the shell's `FocusSearch` runs.
/// That is kept on purpose: Cmd+F always searches. While an overlay is open,
/// `AppShell::focus_search` leaves the focus alone; see
/// docs/redesign/p0-01-gpui-kit.md.
#[gpui::test]
fn cmd_f_focuses_the_search_from_the_shell_and_from_a_text_field(cx: &mut TestAppContext) {
    let (window, shell) = open_shell(cx);

    // Focus on the shell itself: Cmd+F is the vault search.
    window
        .update(cx, |_, window, cx| {
            let focus = shell.read(cx).focus.clone();
            window.focus(&focus, cx);
        })
        .unwrap();
    cx.run_until_parked();
    cx.simulate_keystrokes(window.into(), "cmd-f");
    assert_eq!(
        shell.read_with(cx, |shell, _| shell.focus_search_calls),
        1,
        "Cmd+F outside a text field must focus the vault search"
    );

    // Focus in a text field: the field passes Cmd+F on to the shell.
    window
        .update(cx, |_, window, cx| {
            let field = shell.read(cx).field.clone();
            field.update(cx, |state, cx| state.focus(window, cx));
        })
        .unwrap();
    cx.run_until_parked();
    cx.simulate_keystrokes(window.into(), "cmd-f");
    assert_eq!(
        shell.read_with(cx, |shell, _| shell.focus_search_calls),
        2,
        "Cmd+F in a focused text field must reach FocusSearch"
    );
}
